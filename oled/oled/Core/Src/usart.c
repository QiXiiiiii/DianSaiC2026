/* ==== UART RX 缓冲区 ==== */
#define UART_BUF_SIZE  120
static uint8_t  u1_buf[UART_BUF_SIZE], u2_buf[UART_BUF_SIZE];
static volatile uint16_t u1_len, u2_len;
volatile uint8_t u1_ready, u2_ready;

static void UART_RX_ISR(UART_HandleTypeDef *h, uint8_t *buf,
    volatile uint16_t *len, volatile uint8_t *ready) {
  if (__HAL_UART_GET_FLAG(h, UART_FLAG_RXNE)) {
    uint8_t b = (uint16_t)READ_REG(h->Instance->DR);
    if (*ready == 0 && *len < UART_BUF_SIZE - 1) {
      buf[(*len)++] = b;
    }
    __HAL_UART_CLEAR_FLAG(h, UART_FLAG_RXNE);
  }
  if (__HAL_UART_GET_FLAG(h, UART_FLAG_IDLE)) {
    *ready = 1;
    buf[*len] = 0;
    (void)(uint16_t)READ_REG(h->Instance->DR);
  }
}

void USART1_IRQHandler(void) {
  UART_RX_ISR(&huart1, u1_buf, &u1_len, &u1_ready);
}

void USART2_IRQHandler(void) {
  UART_RX_ISR(&huart2, u2_buf, &u2_len, &u2_ready);
}

uint8_t* u1_get_data(void) { return u1_buf; }
uint8_t  u1_is_ready(void) { return u1_ready; }
void     u1_clear(void)     { u1_len = 0; u1_ready = 0; }

uint8_t* u2_get_data(void) { return u2_buf; }
uint8_t  u2_is_ready(void) { return u2_ready; }
void     u2_clear(void)     { u2_len = 0; u2_ready = 0; }

